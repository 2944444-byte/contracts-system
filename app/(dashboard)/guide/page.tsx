export default function GuidePage() {
  const [open, setOpen] = useState<Record<string, boolean>>({ routine: true });
  const { access } = useAccess();
  // Same gate as the users screen itself: whoever can't open /users gets the
  // "contact the system owner" variant instead of user-management guidance.
  const canManageUsers = !access || canAccessRoute(access, "/users");
  const sections = SECTIONS.map(function(s) { return (s.id === "admin" && !canManageUsers) ? ADMIN_SECTION_LIMITED : s; });
  return (
    <div className="max-w-4xl mx-auto">
      <PageHero title="מדריך למשתמש" icon="📖" tone="blue"
        subtitle="שגרת העבודה, מסך-מסך — תמיד בגרסה העדכנית"
        actions={<button onClick={function(){ if (typeof window !== "undefined") window.print(); }}
          className="rounded-xl bg-white/15 hover:bg-white/25 border border-white/30 px-4 py-2 text-sm font-bold text-white">🖨 הדפס / PDF</button>} />

      {/* Print opens everything; the screen keeps the accordion. */}
      <style>{`@media print { .guide-body { display: block !important; } .no-print { display: none !important; } }`}</style>

      <div className="no-print flex flex-wrap gap-1.5 mb-4">
        {sections.map(function(s) {
          return (
            <a key={s.id} href={"#g-" + s.id}
              onClick={function(){ setOpen(function(p){ return { ...p, [s.id]: true }; }); }}
              className="rounded-full border border-slate-200 bg-white px-3 py-1 text-xs font-semibold text-slate-600 hover:bg-blue-50 hover:text-blue-700">
              {s.icon} {s.title.split(" — ")[0]}
            </a>
          );
        })}
      </div>

      <div className="space-y-3">
        {sections.map(function(s) {
          const isOpen = !!open[s.id];
          return (
            <div key={s.id} id={"g-" + s.id} className="rounded-xl border border-slate-200 bg-white overflow-hidden">
              <button onClick={function(){ setOpen(function(p){ return { ...p, [s.id]: !p[s.id] }; }); }}
                className="w-full flex items-center justify-between px-4 py-3 text-right hover:bg-slate-50">
                <span className="font-bold text-slate-800 text-sm">{s.icon} {s.title}</span>
                <span className="no-print text-slate-400 text-xs">{isOpen ? "▲" : "▼"}</span>
              </button>
              <div className={"guide-body px-4 pb-4 " + (isOpen ? "block" : "hidden")}>{s.body}</div>
            </div>
          );
        })}
      </div>

      <div className="text-center text-[11px] text-slate-400 mt-6 mb-4">
        המדריך מתעדכן יחד עם התוכנה · לשאלות שאינן כאן — מסך ההגדרות או מנהל המערכת
      </div>
    </div>
  );
}
